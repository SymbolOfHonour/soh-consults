const GREEN = '#006837', DARK = '#0f172a', BORDER = '#cbd5e1';
export function wrapReportText(ctx: CanvasRenderingContext2D, text: string, width: number): string[] {
  const lines: string[] = []; let line = '';
  for (const word of text.split(/\s+/)) {
    if (line && ctx.measureText(line + ' ' + word).width > width) { lines.push(line); line = ''; }
    if (ctx.measureText(word).width > width) {
      if (line) { lines.push(line); line = ''; }
      let part = '';
      for (const char of word) {
        if (part && ctx.measureText(part + char).width > width) { lines.push(part); part = ''; }
        part += char;
      }
      line = part;
    } else line += (line ? ' ' : '') + word;
  }
  if (line) lines.push(line);
  return lines.length ? lines : [''];
}
function text(ctx: CanvasRenderingContext2D, value: string, x: number, y: number, width: number, lineHeight = 24) {
  const lines = wrapReportText(ctx, value, width);
  lines.forEach((line, index) => ctx.fillText(line, x, y + index * lineHeight));
  return lines.length * lineHeight;
}
function box(ctx: CanvasRenderingContext2D, x: number, y: number, w: number, h: number, fill = '#fff') {
  ctx.beginPath(); ctx.roundRect(x, y, w, h, 10); ctx.fillStyle = fill; ctx.fill(); ctx.strokeStyle = BORDER; ctx.lineWidth = 2; ctx.stroke();
}
function band(ctx: CanvasRenderingContext2D, title: string, x: number, y: number, w: number) {
  ctx.fillStyle = GREEN; ctx.fillRect(x,y,w,44); ctx.font = '700 18px Arial'; ctx.fillStyle = '#fff'; ctx.fillText(title,x+22,y+29);
}
async function logoImage() {
  return new Promise<HTMLImageElement | null>(resolve => {
    const image = new Image();
    const timeout = window.setTimeout(() => resolve(null), 4000);
    image.onload = () => { clearTimeout(timeout); resolve(image); };
    image.onerror = () => { clearTimeout(timeout); resolve(null); };
    image.src = '/soh-logo.jpg';
  });
}
