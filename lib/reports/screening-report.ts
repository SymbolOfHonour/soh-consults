export async function downloadScreeningReport(data: ScreeningReport, kind: 'pdf'|'jpg') {
  const pages=await buildScreeningReport(data);
  const filename=`${data.school}_Screening_Report_${data.candidate.trim().replace(/[^a-z0-9]+/gi,'_')||'Candidate'}`;
  if(kind==='pdf'){
    const {jsPDF}=await import('jspdf');const pdf=new jsPDF({orientation:'portrait',unit:'mm',format:'a4',compress:true});
    pages.forEach((canvas,i)=>{if(i)pdf.addPage();pdf.addImage(canvas.toDataURL('image/jpeg',.97),'JPEG',0,0,210,297,undefined,'FAST');});pdf.save(filename+'.pdf');
  }else{
    // Keep every page in the image export, including longer source/validation notes.
    const image=document.createElement('canvas');image.width=1240;image.height=1754*pages.length;const ctx=image.getContext('2d');if(!ctx)throw new Error('Unable to create image report.');
    pages.forEach((canvas,i)=>ctx.drawImage(canvas,0,i*1754));
    const blob=await new Promise<Blob>((resolve,reject)=>image.toBlob(value=>value?resolve(value):reject(new Error('Unable to encode JPG.')),'image/jpeg',.97));
    const url=URL.createObjectURL(blob);const link=document.createElement('a');link.href=url;link.download=filename+'.jpg';document.body.appendChild(link);link.click();link.remove();window.setTimeout(()=>URL.revokeObjectURL(url),1000);
  }
}
